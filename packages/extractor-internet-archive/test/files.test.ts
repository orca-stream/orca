import { describe, expect, it } from "vite-plus/test";
import { videoGroups } from "../src/files.ts";
import type { IaFile } from "../src/schema.ts";

function file(name: string, format: string, extra: Partial<IaFile> = {}): IaFile {
  return {
    name,
    format,
    source: extra.original ? "derivative" : "original",
    original: undefined,
    length: undefined,
    size: undefined,
    height: undefined,
    md5: undefined,
    title: undefined,
    ...extra,
  };
}

describe("videoGroups", () => {
  it("prefers the h.264 derivative over an MPEG1 original Jellyfin would transcode", () => {
    const [group] = videoGroups([
      file("X.MPG", "MPEG1", { size: 200 }),
      file("X.mp4", "h.264", { original: "X.MPG", height: 240, size: 100 }),
      file("X_512kb.mp4", "512Kb MPEG4", { original: "X.MPG", height: 240, size: 90 }),
      file("X.ogv", "Ogg Video", { original: "X.MPG", height: 304, size: 80 }),
      file("X.gif", "Animated GIF", { original: "X.MPG" }),
      file("X.autogenerated.vtt", "Web Video Text Tracks"),
    ]);
    expect(group?.best.name).toBe("X.mp4");
  });

  it("prefers an mp4 or mkv original over everything", () => {
    const [group] = videoGroups([
      file("e.mp4", "MPEG4", { height: 240 }),
      file("e.ogv", "Ogg Video", { original: "e.mp4", height: 300 }),
    ]);
    expect(group?.best.name).toBe("e.mp4");
  });

  it("falls to the h.264 derivative when the original is an AVI or an m4v", () => {
    const groups = videoGroups([
      file("a.avi", "Cinepack"),
      file("a.mp4", "h.264", { original: "a.avi" }),
      file("b.m4v", "MPEG4", { height: 240 }),
      file("b.mp4", "h.264", { original: "b.m4v", height: 480 }),
    ]);
    expect(groups.map((g) => g.best.name)).toEqual(["a.mp4", "b.mp4"]);
  });

  it("settles for a lower tier when it is all there is, and takes the taller file within a tier", () => {
    const [low] = videoGroups([
      file("c.avi", "Cinepack"),
      file("c.ogv", "Ogg Video", { original: "c.avi" }),
    ]);
    expect(low?.best.name).toBe("c.avi");

    const [tall] = videoGroups([
      file("d_240.mp4", "h.264", { original: "d.avi", height: 240 }),
      file("d_480.mp4", "h.264", { original: "d.avi", height: 480 }),
    ]);
    expect(tall?.best.name).toBe("d_480.mp4");
  });

  it("ignores thumbnails, torrents and metadata, and groups one video per original", () => {
    const groups = videoGroups([
      file("__ia_thumb.jpg", "Item Tile"),
      file("t.thumbs/e_000001.jpg", "Thumbnail", { original: "e.mp4" }),
      file("item_archive.torrent", "Archive BitTorrent"),
      file("item_meta.xml", "Metadata"),
      file("e.mp4", "MPEG4"),
      file("e.ogv", "Ogg Video", { original: "e.mp4" }),
    ]);
    expect(groups).toHaveLength(1);
  });

  it("carries the duration of the chosen file, or of its original", () => {
    const [group] = videoGroups([
      file("e.avi", "Cinepack", { length: 1500 }),
      file("e.mp4", "h.264", { original: "e.avi" }),
    ]);
    expect(group?.best.name).toBe("e.mp4");
    expect(group?.durationSec).toBe(1500);
  });
});
