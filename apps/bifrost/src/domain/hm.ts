import type { Config } from "./config.ts";
import { JELLYFIN_SERVICE } from "./containers.ts";
import { BifrostError } from "./errors.ts";
import { jellyfinPathOf } from "./media.ts";

/** Names and paths that are properties of the H&M image, not of the host. */
export const HM_SERVICE = "orca-hm";
export const HM_IMAGE_REPOSITORY = "orca-hm";
export const HM_CONTAINER_DB_FILE = "/data/hm.sqlite";
export const HM_CONTAINER_DATA_DIR = "/data";
/** Where the repository keeps the Dockerfile, relative to the build context (the repo root). */
export const HM_DOCKERFILE = "apps/hm-server/Dockerfile";
export const HM_SHM_SIZE = "1gb";
export const HM_MEM_LIMIT = "1536m";
/** The dedicated system user H&M runs as; its primary group is `jellyfin`, which reads what it writes. */
export const HM_USER = "orca-hm";
/** Creates the H&M system user when it is missing (idempotent). */
export const HM_CREATE_USER_COMMAND = `id -u ${HM_USER} >/dev/null 2>&1 || useradd --system --no-create-home --shell /usr/sbin/nologin --gid jellyfin ${HM_USER}`;
export const HM_API_KEY_APP = "Orca H&M";
/** Files under `hm.dataDir` on the host. */
export const HM_ENV_FILE = "hm.env";
export const HM_DATA_SUBDIR = "data";
/** Absolute host path of the directory bind-mounted into the container: the SQLite database lives here. */
export const hmDataPath = (hm: { dataDir: string }) => `${hm.dataDir}/${HM_DATA_SUBDIR}`;
export const HM_SRC_SUBDIR = "src";
/** Holds the image tag the compose file should run; written once an image is built. */
export const HM_IMAGE_MARKER = "image";
/** Length of the commit id in the image tag. */
export const HM_TAG_LENGTH = 12;

export interface HmRuntime {
  uid: number;
  gid: number;
  /** Full image reference, e.g. `orca-hm:0123456789ab`. */
  image: string;
}

type HmConfig = NonNullable<Config["hm"]>;

export function hmImageTag(commit: string): string {
  if (!/^[0-9a-f]{40,64}$/.test(commit)) {
    throw new BifrostError(`"${commit}" is not a full commit id.`);
  }
  return `${HM_IMAGE_REPOSITORY}:${commit.slice(0, HM_TAG_LENGTH)}`;
}

/** The path the TV library has inside both containers. */
export function hmMediaPath(cfg: Config, hm: HmConfig): string {
  const path = jellyfinPathOf(cfg.host, hm.mediaDir);
  if (!path)
    throw new BifrostError(`hm.mediaDir ${hm.mediaDir} is not under a Jellyfin media mount.`);
  return path;
}

export function hmService(cfg: Config, rt: HmRuntime): Record<string, unknown> {
  const hm = cfg.hm!;
  const mediaPath = hmMediaPath(cfg, hm);
  return {
    image: rt.image,
    container_name: HM_SERVICE,
    user: `${rt.uid}:${rt.gid}`,
    // The compose bridge would make H&M reach Jellyfin from 172.x, which Jellyfin's local-network
    // list rejects. On the host network it connects from the LAN address like any other client.
    network_mode: "host",
    shm_size: HM_SHM_SIZE,
    mem_limit: HM_MEM_LIMIT,
    env_file: [`${hm.dataDir}/${HM_ENV_FILE}`],
    volumes: [
      `${hm.dataDir}/${HM_DATA_SUBDIR}:${HM_CONTAINER_DATA_DIR}`,
      `${hm.mediaDir}:${mediaPath}`,
    ],
    depends_on: { [JELLYFIN_SERVICE]: { condition: "service_started" } },
    restart: "unless-stopped",
    healthcheck: {
      test: [
        "CMD",
        "node",
        "-e",
        `fetch('http://127.0.0.1:${hm.port}/health').then(r=>process.exit(r.ok?0:1),()=>process.exit(1))`,
      ],
      interval: "30s",
      timeout: "5s",
      retries: 3,
      start_period: "20s",
    },
  };
}

/** Values go into a compose `env_file`: no interpolation, quoting or line breaks to worry about. */
const SAFE_ENV_VALUE = /^[^\s$"'`\\]+$/;

/** The environment file for the H&M container. The only place its secrets are written. */
export function hmEnvFile(
  cfg: Config,
  secrets: { apiKey: string; contactEmail?: string | undefined },
): string {
  const hm = cfg.hm!;
  const mediaPath = hmMediaPath(cfg, hm);
  const entries: [string, string][] = [
    // Host networking: it listens on the LAN address itself, never on every interface.
    ["HOST", cfg.host.address],
    ["PORT", String(hm.port)],
    ["DB_FILE", HM_CONTAINER_DB_FILE],
    ["MEDIA_ROOT", mediaPath],
    ["JELLYFIN_MEDIA_ROOT", mediaPath],
    ["JELLYFIN_URL", `http://${cfg.host.address}:${cfg.jellyfin.port}`],
    ["JELLYFIN_API_KEY", secrets.apiKey],
  ];
  if (secrets.contactEmail) entries.push(["CONTACT_EMAIL", secrets.contactEmail]);
  for (const [k, v] of entries) {
    if (!SAFE_ENV_VALUE.test(v)) {
      throw new BifrostError(
        `${k} contains whitespace or shell characters; it cannot go in the env file.`,
      );
    }
  }
  return `# Generated by Bifrost. Contains secrets: root-only.\n${entries.map(([k, v]) => `${k}=${v}`).join("\n")}\n`;
}
