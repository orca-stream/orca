import { stringify } from "yaml";
import type { Config } from "./config.ts";
import { BifrostError } from "./errors.ts";
import { HM_SERVICE, type HmRuntime, hmService } from "./hm.ts";
import { JELLYFIN_CONTAINER_DISCOVERY_PORT, JELLYFIN_CONTAINER_HTTP_PORT } from "./containers.ts";
import { mediaMounts, mediaRoot } from "./media.ts";

export { mediaRoot };

export interface ComposeIds {
  /** uid and gid of the dedicated `jellyfin` system user on the host. */
  uid: number;
  gid: number;
  /** GID of the host's `render` group, so the container can open the render device. */
  renderGid: number;
}

export const COMPOSE_FILE = "compose.yaml";
export { JELLYFIN_CONTAINER_DISCOVERY_PORT, JELLYFIN_CONTAINER_HTTP_PORT };

/**
 * The docker-compose file for the Jellyfin container. Ports are published on the LAN address only:
 * Docker's DNAT happens before ufw sees the packet, so binding is the real access control.
 */
export function renderCompose(cfg: Config, ids: ComposeIds, hm?: HmRuntime): string {
  const { host, jellyfin } = cfg;
  if (host.address === "0.0.0.0") {
    throw new BifrostError(
      "Refusing to publish ports on 0.0.0.0: set host.address to the LAN address.",
    );
  }
  const media = mediaMounts(host);
  const doc = {
    services: {
      jellyfin: {
        image: jellyfin.image,
        container_name: "jellyfin",
        user: `${ids.uid}:${ids.gid}`,
        group_add: [String(ids.renderGid)],
        devices: [`${host.renderDevice}:${host.renderDevice}`],
        volumes: [
          `${host.dataDir}/config:/config`,
          `${host.dataDir}/cache:/cache`,
          ...media.map((m) => `${m.source}:${m.target}${m.readOnly ? ":ro" : ""}`),
        ],
        ports: [
          `${host.address}:${jellyfin.port}:${JELLYFIN_CONTAINER_HTTP_PORT}/tcp`,
          `${host.address}:${jellyfin.discoveryPort}:${JELLYFIN_CONTAINER_DISCOVERY_PORT}/udp`,
        ],
        environment: { JELLYFIN_PublishedServerUrl: jellyfin.url },
        restart: "unless-stopped",
        healthcheck: {
          test: [
            "CMD",
            "curl",
            "--noproxy",
            "localhost",
            "-fsS",
            `http://localhost:${JELLYFIN_CONTAINER_HTTP_PORT}/health`,
          ],
          interval: "30s",
          timeout: "10s",
          retries: 3,
          // /health misbehaves while the server starts and migrates its database.
          start_period: "120s",
        },
      },
      // Only present when the caller passes a deployed H&M image: without it the output is the Jellyfin-only file.
      ...(hm && cfg.hm ? { [HM_SERVICE]: hmService(cfg, hm) } : {}),
    },
  };
  return `# Generated by Bifrost from bifrost.yaml. Edit the config, not this file.\n${stringify(doc)}`;
}
