import type { Config } from "../domain/config.ts";
import { BifrostError } from "../domain/errors.ts";
import { HM_SERVICE, hmDataPath } from "../domain/hm.ts";
import { DryRunRemoteHost } from "./dry-run-remote-host.ts";
import type { JellyfinAdmin } from "./ports/jellyfin-admin.ts";
import type { RemoteHost } from "./ports/remote-host.ts";
import type { SecretStore } from "./ports/secret-store.ts";
import { backupConfig, resticPreamble, stagePassword } from "./restic.ts";

export interface BackupDeps {
  remote: RemoteHost;
  secrets: SecretStore;
  jellyfin: JellyfinAdmin;
  log: (line: string) => void;
}

/**
 * H&M keeps its SQLite database in `<hm.dataDir>/data`. A live copy of a WAL database is not
 * consistent, so the container is stopped for the snapshot (a few seconds) and started again right
 * after; the EXIT trap does the same if restic fails. The alternatives were rejected: `sqlite3` is
 * not guaranteed on the host, and a backup API call inside the container needs H&M to ship that
 * code path. Only `data/` goes in: `hm.env` is regenerated by `hm up` and `src/` is build scratch.
 * A configured but never deployed H&M has no directory yet, so it is skipped.
 */
function hmBackupLines(configDir: string, hmData: string): string[] {
  return [
    `paths=(${configDir})`,
    `if [ -d ${hmData} ]; then paths+=(${hmData}); [ -z "$hm_was_running" ] || docker stop ${HM_SERVICE} >/dev/null; fi`,
    `restic backup "\${paths[@]}" --exclude ${configDir}/log --exclude-caches`,
    "hm_restart",
  ];
}

/** Defined before the EXIT trap is installed, so the trap can never call a missing function. */
export function hmRestartDefinitions(): string[] {
  return [
    `hm_was_running=$(docker ps -q --filter name='^${HM_SERVICE}$')`,
    `hm_restart() { [ -z "$hm_was_running" ] || docker start ${HM_SERVICE} >/dev/null; hm_was_running=; }`,
  ];
}

/**
 * Jellyfin's own database backup first (the live database is locked, so a plain file copy is not
 * consistent), then a restic snapshot of the config directory and retention.
 */
export async function backup(
  deps: BackupDeps,
  cfg: Config,
  opts: { dryRun: boolean },
): Promise<void> {
  const { jellyfin, secrets, log } = deps;
  const remote = opts.dryRun ? new DryRunRemoteHost(deps.remote, log) : deps.remote;
  const b = backupConfig(cfg);
  const configDir = `${cfg.host.dataDir}/config`;

  if (opts.dryRun) {
    log("would  ask Jellyfin for a consistent database backup");
  } else {
    const manifest = await jellyfin.createBackup();
    log(`Jellyfin backup created: ${manifest.Path}`);
  }

  await stagePassword(remote, secrets, b.passwordSecret);
  const hm = cfg.hm;
  const hmData = hm ? hmDataPath(hm) : undefined;
  const script = [
    ...(hm ? hmRestartDefinitions() : []),
    ...resticPreamble(b, hm ? ["hm_restart"] : []),
    // Keep only the two newest of Jellyfin's own zips: restic keeps the history.
    `{ ls -1t ${configDir}/data/backups/*.zip 2>/dev/null || true; } | tail -n +3 | xargs -r rm -f`,
    "restic cat config >/dev/null 2>&1 || restic init",
    ...(hmData
      ? hmBackupLines(configDir, hmData)
      : [`restic backup ${configDir} --exclude ${configDir}/log --exclude-caches`]),
    `restic forget --keep-daily ${b.keep.daily} --keep-weekly ${b.keep.weekly} --prune`,
    "",
  ].join("\n");
  const res = await remote.exec(script, { sudo: true });
  if (res.code !== 0)
    throw new BifrostError(`restic failed (exit ${res.code}):\n${res.stderr.trim()}`);
  log("Backup done.");
}
